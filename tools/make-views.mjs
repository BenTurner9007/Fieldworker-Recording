// Builds supabase/views.sql from js/schema.js, so the database views always
// match the app's fields. Run after changing js/schema.js:
//
//   node tools/make-views.mjs
//
// then paste supabase/views.sql into the Supabase SQL Editor and click Run.
import { writeFileSync } from 'node:fs';
import { TYPES, RELATIONSHIPS } from '../js/schema.js';

const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const RESERVED = new Set(['number', 'type', 'date', 'base', 'length', 'order', 'group', 'user']);

function column(f) {
  const v = `r.data ->> '${f.key}'`;
  let name = snake(f.key);
  if (RESERVED.has(name)) name = `${name}_`;
  if (name === 'date_') name = 'record_date';
  if (name === 'length_') name = 'length_m';
  if (name === 'base_') name = 'base_shape';
  switch (f.type) {
    case 'number': return `  nullif(${v}, '')::numeric as ${name}`;
    case 'date': return `  nullif(${v}, '')::date as ${name}`;
    case 'checkbox': return `  coalesce((${v})::boolean, false) as ${name}`;
    default: return `  nullif(${v}, '') as ${name}`;
  }
}

const relLabels = Object.entries(RELATIONSHIPS)
  .map(([k, l]) => `when '${k}' then '${l.replace(/'/g, "''")}'`).join(' ');

let sql = `-- Export views: one tidy table per record type, plus stratigraphic relationships.
-- GENERATED by tools/make-views.mjs from js/schema.js. Don't edit by hand.
-- Paste into Supabase > SQL Editor and Run (after schema.sql).
-- Deleted records are left out. Every view has a geom column (EPSG:27700) for QGIS / ArcGIS Pro.
`;

for (const [type, def] of Object.entries(TYPES)) {
  const name = `fw_${def.plural.toLowerCase()}`;
  const cols = [
    '  r.id',
    '  p.site_code',
    `  ${def.prefix ? `'${def.prefix}' || ` : ''}r.number as number`,
    ...def.fields.map(column),
  ];
  if (type === 'context') {
    cols.push(`  (select string_agg((case x ->> 'rel' ${relLabels} else x ->> 'rel' end) || ' ' || (x ->> 'target'), '; ')
     from jsonb_array_elements(coalesce(r.data -> 'relationships', '[]'::jsonb)) x) as relationships`);
  }
  cols.push(
    "  r.data -> 'location' ->> 'gridRef' as grid_ref",
    "  nullif(r.data -> 'location' ->> 'accuracy', '')::numeric as gps_accuracy_m",
    '  r.latitude', '  r.longitude', '  r.easting', '  r.northing', '  r.geom',
    '  r.updated_by', '  r.updated_at', '  r.synced_at',
  );
  sql += `
drop view if exists public.${name};
create view public.${name} with (security_invoker = true) as
select
${cols.join(',\n')}
from public.fw_records r
join public.fw_projects p on p.id = r.project_id
where r.type = '${type}' and not r.deleted and not p.deleted;
grant select on public.${name} to authenticated;
`;
}

sql += `
-- One row per relationship: handy for Harris matrix software or spreadsheets.
drop view if exists public.fw_relationships;
create view public.fw_relationships with (security_invoker = true) as
select
  p.site_code,
  r.number as context,
  case x ->> 'rel' ${relLabels} else x ->> 'rel' end as relationship,
  x ->> 'target' as other_context
from public.fw_records r
join public.fw_projects p on p.id = r.project_id
cross join lateral jsonb_array_elements(coalesce(r.data -> 'relationships', '[]'::jsonb)) x
where r.type = 'context' and not r.deleted and not p.deleted;
grant select on public.fw_relationships to authenticated;
`;

writeFileSync(new URL('../supabase/views.sql', import.meta.url), sql);
console.log('Wrote supabase/views.sql');
